  /// استخراج اسم الباب العربي لحديث البخاري بواسطة رقم الكتاب أو رقم الحديث
  static String getChapterName(int bookIndex, int hadithNumber) {
    if (bookIndex > 0 && arabicNames.containsKey(bookIndex)) {
      return arabicNames[bookIndex]!;
    }
    // البحث بالنطاق عند bookIndex == 0
    for (final r in _ranges) {
      if (hadithNumber >= r.first && hadithNumber <= r.last) {
        return arabicNames[r.bookId] ?? 'صحيح البخاري';
      }
    }
    return 'صحيح البخاري';
  }
